/**
 * Session 1: Code Example 1
 * Program: HelloWorld.java
 * Purpose: First step in Java programming. Demonstrates standard structure,
 *          entry point method, and printing output to the terminal console.
 *
 * How to compile:
 *   javac HelloWorld.java
 *
 * How to run:
 *   java HelloWorld
 */
public class HelloWorld {

    /**
     * The main method is the entry point of every standalone Java application.
     * When you tell the computer "java HelloWorld", execution starts right here!
     *
     * @param args Command line arguments passed into the program (an array of text strings)
     */
    public static void main(String[] args) {
        // System.out.println displays text on the screen and then moves the cursor to a new line.
        System.out.println("==================================================");
        System.out.println("   Welcome to AI-Driven Java Programming (JAVA-I)! ");
        System.out.println("==================================================");
        System.out.println("Hello, World! My Java journey starts right here.");
        System.out.println("I am learning how code turns into instructions for the JVM.");
    }
}
